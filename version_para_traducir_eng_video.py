def leer_srt(srt_path):
    """Lee un archivo SRT y devuelve lista de segmentos"""
    with open(srt_path, 'r', encoding='utf-8') as f:
        contenido = f.read()

    # Patrón para extraer segmentos SRT
    patron = r'(\d+)\n(\d{2}:\d{2}:\d{2},\d{3}) --> (\d{2}:\d{2}:\d{2},\d{3})\n(.*?)(?=\n\n|\Z)'
    segmentos = re.findall(patron, contenido, re.DOTALL)

    return [
        {
            'numero': int(seg[0]),
            'inicio': seg[1],
            'fin': seg[2],
            'texto': seg[3].strip()
        }
        for seg in segmentos
    ]

