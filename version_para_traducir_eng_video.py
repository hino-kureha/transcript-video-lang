def ipa_to_simple(ipa):
    if not ipa: return ""
    mapeo = {
        "æ": "e", "ɑ": "a", "ʌ": "a", "ɔ": "o", "ə": "e",
        "ɪ": "i", "ʊ": "u", "eɪ": "ei", "aɪ": "ai", "ɔɪ": "oi",
        "θ": "z", "ð": "d", "ʃ": "sh", "ʒ": "zh", "tʃ": "ch", "dʒ": "j", "ŋ": "ng"
    }
    for k, v in mapeo.items():
        ipa = re.sub(k, v, ipa, flags=re.IGNORECASE)
    return re.sub(r"[ˈˌ·\s]", "", ipa.lower()).strip()

def pronunciacion_ingles(texto):
    """[ hhai, its lexi luna. kech mi an aktouber 30th... ]"""
    if not texto.strip(): return ""
    tokens = re.findall(r"\w+(?:'\w+)?|[^\w\s]", texto)
    guia = []
    for token in tokens:
        if re.match(r"[^\w']", token):
            guia.append(token)
            continue
        palabra = token.lower()
        if palabra in cache_en:
            pron = cache_en[palabra]
        else:
            try:
                ipa = eng_to_ipa(palabra)
                if ipa and "*" not in ipa:
                    pron = ipa_to_simple(ipa)
                else: pron = palabra
            except: pron = palabra
            if pron == palabra:
                try:
                    phones = pronouncing.phones_for_word(palabra)
                    if phones:
                        arp = re.sub(r'[0-9]', '', phones[0])
                        pron = arp.replace('AA','a').replace('AE','e').replace('AH','a')\
                                  .replace('AO','o').replace('AW','au').replace('AY','ai')\
                                  .replace('EH','e').replace('ER','er').replace('EY','ei')\
                                  .replace('IH','i').replace('IY','i').replace('OW','ou')\
                                  .replace('OY','oi').replace('UH','u').replace('UW','u')
                        pron = re.sub(r"[ˈˌ·\s]", "", pron.lower())
                except: pron = palabra
            cache_en[palabra] = pron
        if token[0].isupper() and len(token) > 1:
            pron = pron.capitalize()
        guia.append(pron)
    return " ".join(guia).strip()

def pronunciacion_ruso(texto):
    """[ privet, eto leksi luna. vstrechayte menya... ]"""
    if not texto.strip(): return ""
    tokens = re.findall(r"\w+|[^\w\s]", texto)
    guia = []
    for token in tokens:
        if re.match(r"[^\w]", token):
            guia.append(token)
            continue
        palabra = token
        if palabra in cache_ru:
            pron = cache_ru[palabra]
        else:
            try:
                roman = to_latin(palabra, "ru").lower()
                roman = roman.replace("kh","j").replace("zh","sh").replace("ch","ch")
                pron = re.sub(r"[ˈˌ·\s]", "", roman)
            except:
                pron = palabra.lower()
            cache_ru[palabra] = pron
        if token[0].isupper():
            pron = pron.capitalize()
        guia.append(pron)
    return " ".join(guia).strip()

